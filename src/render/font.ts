const W = 5, H = 7, ADV = 6;
const atlases = new Map<string, { canvas: Canvas; index: Map<string, number> }>();

function atlas(color: string) {
  let a = atlases.get(color);
  if (a) return a;
  const keys = Object.keys(G);
  const canvas = makeCanvas(keys.length * ADV, H);
  const x = ctx2d(canvas);
  x.fillStyle = color;
  const index = new Map<string, number>();
  keys.forEach((k, i) => {
    index.set(k, i);
    const bits = G[k].padEnd(35, '.');
    for (let p = 0; p < 35; p++) if (bits[p] === '#') x.fillRect(i * ADV + (p % W), Math.floor(p / W), 1, 1);
  });
  a = { canvas, index };
  atlases.set(color, a);
  return a;
}

export const textWidth = (text: string, scale = 1) => (text.length * ADV - 1) * scale;

/** Draws bitmap text in screen space; lowercase is drawn as uppercase. */
export function drawText(ctx: Ctx, text: string, x: number, y: number, color = '#fff', scale = 1,
  align: 'left' | 'center' | 'right' = 'left', shadow = true): void {
  const t = text.toUpperCase();
  const sx = Math.round(align === 'left' ? x : align === 'center' ? x - textWidth(t, scale) / 2 : x - textWidth(t, scale));
  const sy = Math.round(y);
  if (shadow) blit(ctx, t, sx + scale, sy + scale, '#000', scale);
  blit(ctx, t, sx, sy, color, scale);
}

function blit(ctx: Ctx, t: string, x0: number, y: number, color: string, scale: number) {
  let x = x0;
  const a = atlas(color);
  for (const ch of t) {
    const i = a.index.get(ch) ?? a.index.get('?')!;
    ctx.drawImage(a.canvas, i * ADV, 0, W, H, x, y, W * scale, H * scale);
    x += ADV * scale;
  }
}
